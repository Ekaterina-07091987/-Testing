const { sum, multiply, divide, isEven } = require("../functions");

describe("sum", () => {
  test("sum: возвращает корректную сумму двух чисел", () => {
    // Проверяем, что результат сложения равен ожидаемому числу.
    expect(sum(3, 5)).toBe(8);
  });

  test("sum: корректно работает с отрицательными числами", () => {
    // Проверяем результат сложения двух отрицательных чисел.
    expect(sum(-3, -5)).toBe(-8);
  });
});

describe("multiply", () => {
  test("multiply: возвращает корректное произведение", () => {
    // Проверяем, что результат умножения равен ожидаемому числу.
    expect(multiply(4, 3)).toBe(12);
  });

  test("multiply: возвращает 0 при умножении на 0", () => {
    // Проверяем, что произведение числа на 0 равно 0.
    expect(multiply(7, 0)).toBe(0);
  });
});

describe("divide", () => {
  test("divide: возвращает корректный результат деления", () => {
    // Проверяем, что результат деления равен ожидаемому числу.
    expect(divide(10, 2)).toBe(5);
  });

  test("divide: выбрасывает ошибку при делении на 0", () => {
    // Проверяем, что деление на 0 выбрасывает ошибку с нужным сообщением.
    expect(() => divide(10, 0)).toThrow("Деление на ноль");
  });
});

describe("isEven", () => {
  test("isEven: возвращает true для чётных чисел", () => {
    // Проверяем, что для чётного числа результат — true.
    expect(isEven(8)).toBe(true);
  });

  test("isEven: возвращает false для нечётных чисел", () => {
    // Проверяем, что для нечётного числа результат — false.
    expect(isEven(7)).toBe(false);
  });
});